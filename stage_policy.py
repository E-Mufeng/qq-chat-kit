# ============================ 阶段推进 / 收敛 ============================

def stage_index(stage: str) -> int:
    return STAGE_ORDER.index(stage) if stage in STAGE_ORDER else 0


def clamp_stage(current: str, proposed: str) -> tuple[str, str]:
    """收敛 LLM 提出的阶段：一次最多前进一级，回退不限；未知值回落到当前。

    返回 (最终阶段, 说明)。说明用于日志，便于发现模型乱跳。
    """
    cur = current if current in STAGE_ORDER else "初识"
    if proposed not in STAGE_ORDER:
        return cur, f"模型给出的阶段 '{proposed}' 非法，保持 {cur}"
    ci, pi = stage_index(cur), stage_index(proposed)
    if pi <= ci:
        return proposed, f"{cur} → {proposed}" if pi < ci else f"保持 {cur}"
    if pi - ci > 1:
        return STAGE_ORDER[ci + 1], f"模型想跳到 {proposed}，收敛为 {STAGE_ORDER[ci + 1]}（一次最多进一级）"
    return proposed, f"{cur} → {proposed}"


def night_adjust(stage: str, hour: int | None = None) -> tuple[str, str]:
    """深夜（23:00-07:00）自动降一档热度。

    深夜直球暧昧最容易让人反感也最像骚扰，所以这个时段把说辞压回上一档；
    但**不改动真实关系阶段**，只影响本轮生成与校验。
    """
    if hour is None:
        from datetime import datetime
        hour = datetime.now().hour
    if not (23 <= hour or hour < 7):
        return stage, ""
    i = stage_index(stage)
    if i <= 0:
        return stage, ""
    prev = STAGE_ORDER[i - 1]
    return prev, f"深夜时段（{hour}点）热度降一档：{stage} → {prev}（真实阶段不变）"


def earlier(a: str, b: str) -> str:
    """取两个阶段中更靠前（更保守）的那个。"""
    return a if stage_index(a) <= stage_index(b) else b


