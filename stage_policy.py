def check_boundary(stage: str, reply: str) -> list[str]:
    """返回越界说明列表；空列表 = 通过。"""
    if not reply:
        return ["回复为空"]
    cur = stage_index(stage if stage in STAGE_ORDER else "初识")
    hits: list[str] = []
    for cat, pat in _PATTERNS:
        if not pat.search(reply):
            continue
        need = _CAT_MIN_STAGE[cat]
        if need == 99:
            hits.append(f"[红线] 命中「{cat}」：任何阶段都不允许")
        elif cur < need:
            need_stage = STAGE_ORDER[need]
            hits.append(f"[越界] 当前「{stage}」命中「{cat}」，至少要到「{need_stage}」才能这么说")
        else:
            hits.append(f"[提示] 命中「{cat}」（本阶段允许，但注意分寸）")
    return hits


def is_blocked(hits: list[str]) -> bool:
    """是否存在必须拦截的问题（红线或越界）。纯提示不算。"""
    return any(h.startswith(("[红线]", "[越界]")) for h in hits)


# ============================ prompt 注入 ============================

def stage_block(stage: str) -> str:
    """生成注入 system prompt 的阶段准则段。"""
    s = stage if stage in STAGE_ORDER else "初识"
    cfg = STAGES[s]
    lines = [
        f"【当前关系阶段：{s}】（第 {stage_index(s) + 1}/{len(STAGE_ORDER)} 档，亲密度上限 {STAGE_INTIMACY[s]}/100）",
        f"本阶段唯一目标：{cfg['goal']}",
        f"语气：{cfg['tone']}",
        f"长度：{cfg['len']}",
        "可以做：",
    ]
    lines += [f"  + {x}" for x in cfg["allow"]]
    lines.append("绝对不可以：")
    lines += [f"  - {x}" for x in cfg["forbid"]]
    lines.append("全局红线（任何阶段）：")
    lines += [f"  ! {x}" for x in GLOBAL_BAN]
    lines += [
        f"示例 ✓：{cfg['sample_ok']}",
        f"示例 ✗：{cfg['sample_bad']}",
        f"推进条件：{cfg['advance_when']}",
        f"阶段只能逐级上升，一次最多前进一档；回退不限。当前是「{s}」，"
        f"因此本轮输出的 stage 只能是「{s}」或「{STAGE_ORDER[stage_index(s) + 1]}」"
        f"{'（已是终态）' if stage_index(s) >= len(STAGE_ORDER) - 1 else ''}。",
    ]
    return "\n".join(lines)


